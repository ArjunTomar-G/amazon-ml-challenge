def pair_features(U: Universe, cand: pl.DataFrame) -> pl.DataFrame:
    """cand: q_row, e_row, score, rank (+ anything else, passed through)."""
    pq = cand["q_row"].to_numpy().astype(np.int64)
    pe = cand["e_row"].to_numpy().astype(np.int64)
    F = {}
    # --- token alignment -----------------------------------------------------
    ts = U.name_ts
    tf = token_feats(pq, pe, ts.q_ptr, ts.q_ids, ts.s1_ptr, ts.s1_ids, ts.voc_ptr, ts.voc_buf,
                     ts.idf, ts.ratio, ts.is_num, 0.75)
    for k, nm in enumerate(TOKFEAT_NAMES):
        F["nt_" + nm] = tf[:, k]
    ts = U.legal_ts
    lf = token_feats(pq, pe, ts.q_ptr, ts.q_ids, ts.s1_ptr, ts.s1_ids, ts.voc_ptr, ts.voc_buf,
                     ts.idf, ts.ratio, ts.is_num, 0.99)
    for k in (0, 1, 2):
        F["lg_" + TOKFEAT_NAMES[k]] = lf[:, k]
    F["lg_q_subset"] = ((lf[:, 2] == lf[:, 0]) & (lf[:, 0] < lf[:, 1])).astype(np.float32)
    ts = U.all_ts
    nf_ = token_feats(pq, pe, ts.q_ptr, ts.q_ids, ts.s1_ptr, ts.s1_ids, ts.voc_ptr, ts.voc_buf,
                      ts.idf, ts.ratio, ts.is_num, 0.75)
    for k in (9, 10, 17):
        F["na_" + TOKFEAT_NAMES[k]] = nf_[:, k]
    ts = U.addr_ts
    af = token_feats(pq, pe, ts.q_ptr, ts.q_ids, ts.s1_ptr, ts.s1_ids, ts.voc_ptr, ts.voc_buf,
                     ts.idf, ts.ratio, ts.is_num, 0.8)
    for k, nm in enumerate(TOKFEAT_NAMES):
        if nm in ("markers", "inversions"):
            continue
        F["at_" + nm] = af[:, k]
    nf = num_token_feats(pq, pe, ts.q_ptr, ts.q_ids, ts.s1_ptr, ts.s1_ids, ts.is_num)
    for k, nm in enumerate(["nq", "ne", "match", "qun", "eun"]):
        F["an_" + nm] = nf[:, k]
    ts = U.name_ts
    bf = behaviour_feats(pq, pe, ts.q_ptr, ts.q_ids, ts.s1_ptr, ts.s1_ids,
                         U.bh_same, U.bh_up, U.bh_nohn, U.bh_known)
    for k, nm in enumerate(["min_same", "max_up", "max_nohn", "n_known", "n_unknown"]):
        F["bh_" + nm] = bf[:, k]

    # --- aligned record columns ---------------------------------------------
    qcols = ["n_core", "n_all", "n_alt", "n_glued", "n_legal", "a_all", "a_tok", "a_hn", "a_hnsfx",
             "a_street", "a_locs", "a_state", "a_unit", "hn_num", "n_flags", "a_flags", "n_indic",
             "n_indic_hit", "src", "u_q_s1_same_name", "u_q_dups"]
    ecols = ["n_core", "n_all", "n_glued", "n_legal", "a_all", "a_tok", "a_hn", "a_hnsfx",
             "a_street", "a_locs", "a_state", "a_unit", "hn_num", "n_flags", "a_flags",
             "u_s1_same_name", "u_s1_same_addr", "u_s1_same_hnst"]
    Q = U.q.select(qcols)[pq]
    E = U.s1.select(ecols)[pe]
    lst = lambda df, c: df[c].to_list()

    qn, en = lst(Q, "n_core"), lst(E, "n_core")
    F["rf_n_ratio"] = _rf(fuzz.ratio, qn, en)
    F["rf_n_tset"] = _rf(fuzz.token_set_ratio, qn, en)
    F["rf_n_tsort"] = _rf(fuzz.token_sort_ratio, qn, en)
    F["rf_n_partial"] = _rf(fuzz.partial_ratio, qn, en)
    F["rf_n_jw"] = _rf(JaroWinkler.normalized_similarity, qn, en)
    qg, eg = lst(Q, "n_glued"), lst(E, "n_glued")
    F["rf_g_ratio"] = _rf(fuzz.ratio, qg, eg)
    F["rf_g_partial"] = _rf(fuzz.partial_ratio, qg, eg)
    F["rf_nall_tset"] = _rf(fuzz.token_set_ratio, lst(Q, "n_all"), lst(E, "n_all"))
    qalt = lst(Q, "n_alt")
    alt = _rf(fuzz.token_set_ratio, qalt, en)
    alt[np.array([not s for s in qalt])] = np.nan
    F["rf_alt_tset"] = alt
    qa, ea = lst(Q, "a_tok"), lst(E, "a_tok")
    F["rf_a_ratio"] = _rf(fuzz.ratio, lst(Q, "a_all"), lst(E, "a_all"))
    F["rf_a_tset"] = _rf(fuzz.token_set_ratio, qa, ea)
    F["rf_a_tsort"] = _rf(fuzz.token_sort_ratio, qa, ea)
    F["rf_a_partial"] = _rf(fuzz.partial_ratio, qa, ea)
    qs, es = lst(Q, "a_street"), lst(E, "a_street")
    F["rf_st_ratio"] = _rf(fuzz.ratio, qs, es)
    F["rf_st_tset"] = _rf(fuzz.token_set_ratio, qs, es)
    F["rf_st_jw"] = _rf(JaroWinkler.normalized_similarity, qs, es)
    ql, el = lst(Q, "a_locs"), lst(E, "a_locs")
    F["rf_loc_tset"] = _rf(fuzz.token_set_ratio, ql, el)
    F["rf_loc_partial"] = _rf(fuzz.partial_ratio, ql, el)
    qh, eh = lst(Q, "a_hn"), lst(E, "a_hn")
    F["hn_lev"] = _rf(Levenshtein.distance, qh, eh)
    F["hn_indel"] = _rf(Indel.distance, qh, eh)

    # mask string similarities where one side is empty
    def empty(df, c):
        return (df[c] == "").to_numpy()
    for key, col in [("rf_n_", "n_core"), ("rf_g_", "n_glued"), ("rf_a_", "a_tok"),
                     ("rf_st_", "a_street"), ("rf_loc_", "a_locs")]:
        m = empty(Q, col) | empty(E, col)
        for f in list(F):
            if f.startswith(key):
                F[f][m] = np.nan
    hq_e, he_e = empty(Q, "a_hn"), empty(E, "a_hn")
    hn_missing = hq_e | he_e
    for f in ("hn_lev", "hn_indel"):
        F[f][hn_missing] = np.nan

    # --- house numbers -----------------------------------------------------------
    hq = Q["hn_num"].to_numpy().astype(np.float64)
    he = E["hn_num"].to_numpy().astype(np.float64)
    both = ~np.isnan(hq) & ~np.isnan(he)
    F["hn_q_present"] = (~hq_e).astype(np.float32)
    F["hn_e_present"] = (~he_e).astype(np.float32)
    F["hn_str_eq"] = np.where(hn_missing, np.nan, (Q["a_hn"] == E["a_hn"]).to_numpy()).astype(np.float32)
    d = np.abs(hq - he)
    F["hn_absdiff"] = np.where(both, np.minimum(d, 1e6), np.nan).astype(np.float32)
    F["hn_signdiff"] = np.where(both, np.clip(hq - he, -1e6, 1e6), np.nan).astype(np.float32)
    F["hn_reldiff"] = np.where(both, d / np.maximum(np.maximum(hq, he), 1), np.nan).astype(np.float32)
    lq = Q["a_hn"].str.len_chars().to_numpy().astype(np.float32)
    le = E["a_hn"].str.len_chars().to_numpy().astype(np.float32)
    F["hn_lendiff"] = np.where(hn_missing, np.nan, lq - le)
    indel = F["hn_indel"]
    F["hn_subseq"] = np.where(hn_missing, np.nan,
                              ((indel == np.abs(lq - le)) & (lq != le)).astype(np.float32))
    fq = Q["a_hn"].str.slice(0, 1)
    fe = E["a_hn"].str.slice(0, 1)
    F["hn_first_eq"] = np.where(hn_missing, np.nan, (fq == fe).to_numpy()).astype(np.float32)
    lq_ = Q["a_hn"].str.slice(-1, 1)
    le_ = E["a_hn"].str.slice(-1, 1)
    F["hn_last_eq"] = np.where(hn_missing, np.nan, (lq_ == le_).to_numpy()).astype(np.float32)
    sq_, se_ = Q["a_hnsfx"], E["a_hnsfx"]
    F["hn_sfx_q"] = (sq_ != "").to_numpy().astype(np.float32)
    F["hn_sfx_e"] = (se_ != "").to_numpy().astype(np.float32)
    F["hn_sfx_eq"] = ((sq_ == se_) & (sq_ != "")).to_numpy().astype(np.float32)

    # --- state / unit / legal -------------------------------------------------------
    stq, ste = Q["a_state"], E["a_state"]
    F["state_eq"] = np.where(((stq == "") | (ste == "")).to_numpy(), np.nan,
                             (stq == ste).to_numpy()).astype(np.float32)
    F["unit_q"] = (Q["a_unit"] != "").to_numpy().astype(np.float32)
    F["unit_e"] = (E["a_unit"] != "").to_numpy().astype(np.float32)
    F["unit_eq"] = ((Q["a_unit"] == E["a_unit"]) & (Q["a_unit"] != "")).to_numpy().astype(np.float32)
    F["legal_eq"] = (Q["n_legal"] == E["n_legal"]).to_numpy().astype(np.float32)
    F["legal_q_empty"] = (Q["n_legal"] == "").to_numpy().astype(np.float32)
    F["legal_e_empty"] = (E["n_legal"] == "").to_numpy().astype(np.float32)

    # --- flags -------------------------------------------------------------------
    qnf = Q["n_flags"].to_numpy()
    enf = E["n_flags"].to_numpy()
    qaf = Q["a_flags"].to_numpy()
    eaf = E["a_flags"].to_numpy()
    for k, bit in NF_BITS.items():
        F["qnf_" + k] = ((qnf & bit) > 0).astype(np.float32)
    for k in ("inv", "honor", "upper"):
        F["enf_" + k] = ((enf & NF_BITS[k]) > 0).astype(np.float32)
    for k, bit in AF_BITS.items():
        F["qaf_" + k] = ((qaf & bit) > 0).astype(np.float32)
    for k in ("reorder", "unit", "nohn", "missing"):
        F["eaf_" + k] = ((eaf & AF_BITS[k]) > 0).astype(np.float32)
    ni = Q["n_indic"].to_numpy().astype(np.float32)
    F["q_indic"] = ni
    F["q_indic_miss"] = ni - Q["n_indic_hit"].to_numpy().astype(np.float32)
    F["q_src"] = Q["src"].to_numpy().astype(np.float32)
    F["q_nlen"] = Q["n_core"].str.len_chars().to_numpy().astype(np.float32)
    F["e_nlen"] = E["n_core"].str.len_chars().to_numpy().astype(np.float32)
    F["q_alen"] = Q["a_tok"].str.len_chars().to_numpy().astype(np.float32)
    F["e_alen"] = E["a_tok"].str.len_chars().to_numpy().astype(np.float32)
    # --- universe stats ------------------------------------------------------------
    for c in ("u_q_s1_same_name", "u_q_dups"):
        F[c] = np.minimum(Q[c].to_numpy(), U_CAP).astype(np.float32)
    for c in ("u_s1_same_name", "u_s1_same_addr", "u_s1_same_hnst"):
        F[c] = np.minimum(E[c].to_numpy(), U_CAP).astype(np.float32)
    # --- retrieval (two channels) -----------------------------------------------------
    for col in ("s_all", "r_all", "s_addr", "r_addr"):
        F["ret_" + col] = cand[col].cast(pl.Float32).to_numpy()
    F["ret_rel_all"] = (cand["s_all"] / cand["top_all"]).cast(pl.Float32).to_numpy()
    F["ret_rel_addr"] = (cand["s_addr"] / cand["top_addr"]).cast(pl.Float32).to_numpy()
    F["ret_ncand"] = cand.select(pl.len().over("q_row")).to_series().to_numpy().astype(np.float32)

    out = pl.DataFrame({k: np.asarray(v, dtype=np.float32) for k, v in F.items()})
    return out
