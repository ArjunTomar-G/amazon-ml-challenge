@njit(cache=True)
def _lev_sim(buf, a0, a1, b0, b1, prev, cur):
    la = a1 - a0
    lb = b1 - b0
    if la == 0 or lb == 0:
        return 0.0
    for j in range(lb + 1):
        prev[j] = j
    for i in range(1, la + 1):
        cur[0] = i
        ca = buf[a0 + i - 1]
        for j in range(1, lb + 1):
            cost = 0 if ca == buf[b0 + j - 1] else 1
            v = prev[j - 1] + cost
            d = prev[j] + 1
            if d < v:
                v = d
            ins = cur[j - 1] + 1
            if ins < v:
                v = ins
            cur[j] = v
        for j in range(lb + 1):
            prev[j] = cur[j]
    m = la if la > lb else lb
    return 1.0 - prev[lb] / m


@njit(cache=True)
def _is_prefix(buf, a0, a1, b0, b1):
    la = a1 - a0
    lb = b1 - b0
    n = la if la < lb else lb
    if n < 3:
        return False
    for k in range(n):
        if buf[a0 + k] != buf[b0 + k]:
            return False
    return True


N_TOKFEAT = 18


@njit(parallel=True, cache=True)
def token_feats(pq, pe, q_ptr, q_ids, e_ptr, e_ids, voc_ptr, voc_buf, idf, ratio, is_num,
                soft_thr):
    """Soft token alignment features for aligned pair arrays (pq[i], pe[i])."""
    n = pq.shape[0]
    out = np.full((n, N_TOKFEAT), np.nan, np.float32)
    nb = 1024
    bs = (n + nb - 1) // nb
    for b in prange(nb):
        prev = np.empty(64, np.int64)
        cur = np.empty(64, np.int64)
        esim = np.zeros(MAXTOK, np.float32)
        qpos = np.empty(MAXTOK, np.int64)
        for i in range(b * bs, min(n, (b + 1) * bs)):
            qa = q_ptr[pq[i]]
            qb = min(q_ptr[pq[i] + 1], qa + MAXTOK)
            ea = e_ptr[pe[i]]
            eb = min(e_ptr[pe[i] + 1], ea + MAXTOK)
            nq = qb - qa
            ne = eb - ea
            for k in range(ne):
                esim[k] = 0.0
            n_exact = 0
            n_soft = 0
            idf_match = 0.0
            idf_qun = 0.0
            max_qun = 0.0
            max_rq = -99.0
            sum_rq = 0.0
            n_marker = 0
            sim_sum = 0.0
            nm = 0
            for a in range(nq):
                ta = q_ids[qa + a]
                best = 0.0
                bestk = -1
                for k in range(ne):
                    tb = e_ids[ea + k]
                    if ta == tb and ta >= 0:
                        s = 1.0
                    elif ta < 0 or tb < 0 or is_num[ta] or is_num[tb]:
                        s = 0.0
                    else:
                        a0 = voc_ptr[ta]
                        a1 = voc_ptr[ta + 1]
                        b0 = voc_ptr[tb]
                        b1 = voc_ptr[tb + 1]
                        la = a1 - a0
                        lb = b1 - b0
                        mn = la if la < lb else lb
                        mx = la if la > lb else lb
                        s = 0.0
                        if mn >= 3 and (mx - mn) <= max(2, mx // 3):
                            s = _lev_sim(voc_buf, a0, a1, b0, b1, prev, cur)
                        if s < 0.8 and _is_prefix(voc_buf, a0, a1, b0, b1):
                            s = 0.8
                    if s > best:
                        best = s
                        bestk = k
                    if s > esim[k]:
                        esim[k] = s
                w = idf[ta] if ta >= 0 else 1.0
                if best >= 1.0:
                    n_exact += 1
                if best >= soft_thr:
                    n_soft += 1
                    idf_match += w * best
                    sim_sum += best
                    qpos[nm] = bestk
                    nm += 1
                else:
                    idf_qun += w
                    if w > max_qun:
                        max_qun = w
                    r = ratio[ta] if ta >= 0 else 0.0
                    if r > max_rq:
                        max_rq = r
                    if r > 0.0:
                        sum_rq += r
                    if r > 1.0:
                        n_marker += 1
            idf_eun = 0.0
            max_eun = 0.0
            max_re = -99.0
            n_esoft = 0
            for k in range(ne):
                tb = e_ids[ea + k]
                w = idf[tb] if tb >= 0 else 1.0
                if esim[k] >= soft_thr:
                    n_esoft += 1
                else:
                    idf_eun += w
                    if w > max_eun:
                        max_eun = w
                    r = ratio[tb] if tb >= 0 else 0.0
                    if r > max_re:
                        max_re = r
            inv = 0
            for x in range(nm):
                for y in range(x + 1, nm):
                    if qpos[y] < qpos[x]:
                        inv += 1
            first_match = 0.0
            if nq > 0 and ne > 0:
                ta = q_ids[qa]
                tb = e_ids[ea]
                if ta == tb and ta >= 0:
                    first_match = 1.0
            out[i, 0] = nq
            out[i, 1] = ne
            out[i, 2] = n_exact
            out[i, 3] = n_soft
            out[i, 4] = idf_match
            out[i, 5] = idf_qun
            out[i, 6] = idf_eun
            out[i, 7] = max_qun
            out[i, 8] = max_eun
            out[i, 9] = max_rq if max_rq > -99.0 else np.nan
            out[i, 10] = max_re if max_re > -99.0 else np.nan
            den = idf_match + idf_qun + idf_eun
            out[i, 11] = idf_match / den if den > 0 else np.nan
            out[i, 12] = n_soft / nq if nq > 0 else np.nan
            out[i, 13] = n_esoft / ne if ne > 0 else np.nan
            out[i, 14] = first_match
            out[i, 15] = inv / (nm * (nm - 1) / 2) if nm > 1 else 0.0
            out[i, 16] = sim_sum / nm if nm > 0 else np.nan
            out[i, 17] = n_marker + 0.001 * sum_rq
    return out


