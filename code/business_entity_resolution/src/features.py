NORM_COLS = ["entity_id", "country", "src", "n_all", "n_core", "n_alt", "n_legal", "n_flags",
             "n_indic", "n_indic_hit", "a_all", "a_tok", "a_hn", "a_hnsfx", "a_street", "a_loc",
             "a_state", "a_unit", "a_flags"]

MAXTOK = 48
SIB_OFFSET = 2.0
# Universe-invariant token statistics.  The test universe differs from train in size
# (test US has half the entities of train US) and in distractor density, so every
# statistic must depend on relative frequencies only and must be too coarse for the
# trees to memorise per-token constants:
#   idf   = log(N1 / df1) (a relative frequency, invariant to universe size), rounded
#           to IDF_STEP and capped at IDF_CAP (all rare tokens look alike)
#   ratio = sibling statistic rounded to RATIO_STEP
#   u_*   = universe counts capped at U_CAP
# (v2 used idf / log(N1): a generic noise word such as "center" moved from 0.271 in
# train to 0.283 in test and the trees, which had memorised its exact value, scored
# true "... Center" records 0.99 in validation but 0.70 on test.)
IDF_STEP = 0.25
IDF_CAP = 9.0
RATIO_STEP = 0.5
U_CAP = 3
# Word behaviour (label-free, per universe and country).  For every record and its most
# likely Source-1 candidate (pruner argmax), each word of the record that the candidate's
# name does not contain is an "extra" word; we count how often records carrying it keep the
# candidate's house number (noise on a true match: "Regional Steel" -> "Regional Services",
# French "... et Fils"), shift it upward by 1..BH_UP_MAX (generated sibling business:
# "... Coastal", "... Distribution") or have no house number.  Validated on train labels:
# words with same-rate >= 0.7 are 91-98 % true matches, words with same-rate <= 0.1 are 0-5 %.
# The rates describe what a word *does* in its own universe, so they transfer to a country
# without labels (France), where the IDF-based word identity of US/India cannot.
BH_UP_MAX = 40
BH_MIN_N = 30          # rates of words seen fewer times are unknown (NaN)
BH_STEP = 0.1          # rates are rounded (no per-word constants to memorise)


