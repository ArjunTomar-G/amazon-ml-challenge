@njit(cache=True)
def _behaviour_counts(q_rows, e_rows, q_ptr, q_ids, e_ptr, e_ids, hq, he, V):
    """Per token: occurrences as an extra word, and how many of them keep the house number
    (same), shift it upward by 1..BH_UP_MAX (up) or lack one (nohn)."""
    n = np.zeros(V, np.float64)
    same = np.zeros(V, np.float64)
    up = np.zeros(V, np.float64)
    nohn = np.zeros(V, np.float64)
    for i in range(q_rows.shape[0]):
        qa = q_ptr[q_rows[i]]
        qb = q_ptr[q_rows[i] + 1]
        ea = e_ptr[e_rows[i]]
        eb = e_ptr[e_rows[i] + 1]
        h1 = hq[q_rows[i]]
        h2 = he[e_rows[i]]
        rel = 0
        if h1 < 0 or h2 < 0:
            rel = 3
        elif h1 == h2:
            rel = 1
        elif h1 - h2 >= 1 and h1 - h2 <= BH_UP_MAX:
            rel = 2
        for a in range(qa, qb):
            t = q_ids[a]
            if t < 0:
                continue
            found = False
            for b in range(ea, eb):
                if e_ids[b] == t:
                    found = True
                    break
            if found:
                continue
            n[t] += 1.0
            if rel == 1:
                same[t] += 1.0
            elif rel == 2:
                up[t] += 1.0
            elif rel == 3:
                nohn[t] += 1.0
    return n, same, up, nohn


@njit(parallel=True, cache=True)
def behaviour_feats(pq, pe, q_ptr, q_ids, e_ptr, e_ids, same_r, up_r, nohn_r, known):
    """Behaviour of the record's extra words (w.r.t. this candidate): min same-rate, max
    up-rate, max nohn-rate over words with known behaviour, #known, #unknown extra words."""
    n = pq.shape[0]
    out = np.full((n, 5), np.nan, np.float32)
    for i in prange(n):
        qa = q_ptr[pq[i]]
        qb = q_ptr[pq[i] + 1]
        ea = e_ptr[pe[i]]
        eb = e_ptr[pe[i] + 1]
        mn_same = 2.0
        mx_up = -1.0
        mx_nohn = -1.0
        nk = 0
        nu = 0
        for a in range(qa, qb):
            t = q_ids[a]
            if t < 0:
                continue
            found = False
            for b in range(ea, eb):
                if e_ids[b] == t:
                    found = True
                    break
            if found:
                continue
            if known[t]:
                nk += 1
                if same_r[t] < mn_same:
                    mn_same = same_r[t]
                if up_r[t] > mx_up:
                    mx_up = up_r[t]
                if nohn_r[t] > mx_nohn:
                    mx_nohn = nohn_r[t]
            else:
                nu += 1
        if nk > 0:
            out[i, 0] = mn_same
            out[i, 1] = mx_up
            out[i, 2] = mx_nohn
        out[i, 3] = nk
        out[i, 4] = nu
    return out


@njit(parallel=True, cache=True)
def num_token_feats(pq, pe, q_ptr, q_ids, e_ptr, e_ids, is_num):
    """Exact agreement of numeric address tokens."""
    n = pq.shape[0]
    out = np.zeros((n, 5), np.float32)
    for i in prange(n):
        qa = q_ptr[pq[i]]
        qb = q_ptr[pq[i] + 1]
        ea = e_ptr[pe[i]]
        eb = e_ptr[pe[i] + 1]
        nqn = 0
        nen = 0
        m = 0
        for a in range(qa, qb):
            ta = q_ids[a]
            if ta < 0 or not is_num[ta]:
                continue
            nqn += 1
            for k in range(ea, eb):
                if e_ids[k] == ta:
                    m += 1
                    break
        for k in range(ea, eb):
            tb = e_ids[k]
            if tb >= 0 and is_num[tb]:
                nen += 1
        out[i, 0] = nqn
        out[i, 1] = nen
        out[i, 2] = m
        out[i, 3] = nqn - m
        out[i, 4] = nen - m
    return out


