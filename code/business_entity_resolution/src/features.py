"""Stage 3: pairwise features for (query record, Source-1 entity) candidates.

Feature families
  * token alignment (Numba): soft token matching with a Levenshtein kernel over
    a per-country vocabulary; IDF mass of matched / unexplained tokens; the
    "sibling ratio" of unexplained tokens (see below); order inversions.
  * rapidfuzz string similarities (vectorised C++, multi-threaded cpdist) on
    names, glued names, aliases, addresses, streets, localities.
  * house-number arithmetic (numeric delta, digit subsequence, first/last digit)
  * legal form agreement, record flags, retrieval score/rank
  * label-free universe statistics (chain names, multi-tenant addresses, dups)

The sibling ratio of a token t in a universe/country is
      log((c_S2S3(t)+1) / (c_S1(t)+1)) - log(N_S2S3 / N_S1)
Hard-negative "sibling" businesses are generated by adding words that never
occur in the deduplicated reference (Source 1) - e.g. "northside", "eastgate",
"participations" - so their ratio is extreme.  It is computed without labels,
separately for every universe (train / test) and country, hence it transfers
to countries never seen in training (France).
"""
