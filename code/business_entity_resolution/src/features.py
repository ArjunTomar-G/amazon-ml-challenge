class Universe:
    def __init__(self, split: str):
        self.split = split
        with Timer(f"load universe {split}"):
            self.s1, self.q = load_universe(split, NORM_COLS)
        with Timer(f"token spaces {split}"):
            self.name_ts = TokenSpace(self.s1, self.q, "n_core", stat_col="n_all")
            self.legal_ts = TokenSpace(self.s1, self.q, "n_legal", stat_col="n_all")
            self.all_ts = TokenSpace(self.s1, self.q, "n_all")
            self.addr_ts = TokenSpace(self.s1, self.q, "a_tok")
        with Timer(f"universe stats {split}"):
            self._record_stats()

    def set_behaviour(self, cand: pl.DataFrame):
        """Word-behaviour rates of the name vocabulary from the record-argmax pairs of the
        candidate set (by pruner probability; labels are never used)."""
        best = (cand.select("q_row", "e_row", "p_prune")
                .sort(["q_row", "p_prune"], descending=[False, True])
                .unique(subset="q_row", keep="first"))
        hq = self.q["hn_num"].fill_null(-1).to_numpy().astype(np.int64)
        he = self.s1["hn_num"].fill_null(-1).to_numpy().astype(np.int64)
        ts = self.name_ts
        n, same, up, nohn = _behaviour_counts(
            best["q_row"].to_numpy().astype(np.int64), best["e_row"].to_numpy().astype(np.int64),
            ts.q_ptr, ts.q_ids, ts.s1_ptr, ts.s1_ids, hq, he, ts.V)
        rnd = lambda x: (np.round(x / np.maximum(n, 1.0) / BH_STEP) * BH_STEP).astype(np.float32)
        self.bh_same, self.bh_up, self.bh_nohn = rnd(same), rnd(up), rnd(nohn)
        self.bh_known = n >= BH_MIN_N
        log(f"word behaviour: {int(self.bh_known.sum())} words with >= {BH_MIN_N} extra-word occurrences")

    def _record_stats(self):
        s1, q = self.s1, self.q
        # derived strings used by rapidfuzz features
        extra = lambda df: df.with_columns(
            pl.col("n_core").str.replace_all(" ", "").alias("n_glued"),
            pl.col("a_loc").str.replace_all(r" \| ", " ").alias("a_locs"),
            pl.col("a_hn").str.extract(r"(\d+)", 1).cast(pl.Int64, strict=False).alias("hn_num"),
        )
        s1 = extra(s1)
        q = extra(q)
        # label-free universe statistics
        s1 = s1.with_columns(
            pl.len().over(["country", "n_core"]).alias("u_s1_same_name"),
            pl.len().over(["country", "a_tok"]).alias("u_s1_same_addr"),
            pl.len().over(["country", "a_hn", "a_street"]).alias("u_s1_same_hnst"),
        )
        name_cnt = s1.group_by(["country", "n_core"]).len().rename({"len": "u_q_s1_same_name"})
        q = q.join(name_cnt, on=["country", "n_core"], how="left").with_columns(
            pl.col("u_q_s1_same_name").fill_null(0))
        q = q.with_columns(pl.len().over(["country", "n_core", "a_tok"]).alias("u_q_dups"))
        self.s1 = s1.sort("row")
        self.q = q.sort("row")
        # 64-bit hashes of fields for O(1) equality features
        self.hq, self.he = {}, {}
        for c in ("a_hn", "a_street", "n_core", "n_glued", "a_tok", "n_legal", "a_state", "a_locs"):
            self.hq[c] = self.q[c].hash(seed=3).to_numpy()
            self.he[c] = self.s1[c].hash(seed=3).to_numpy()
            self.hq[c + "_empty"] = (self.q[c] == "").to_numpy()
            self.he[c + "_empty"] = (self.s1[c] == "").to_numpy()


