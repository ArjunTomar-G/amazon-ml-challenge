class TokenSpace:
    """(country, token) vocabulary shared by S1 and query tables for one field.

    Built chunk-wise: only (record, token-hash) numpy arrays and the unique
    vocabulary are ever materialised, so memory stays low on ~12M records."""

    CHUNK = 2_000_000

    def __init__(self, s1: pl.DataFrame, q: pl.DataFrame, col: str, stat_col: str | None = None):
        stat_col = stat_col or col
        voc_parts = []
        r1, h1 = self._explode_all(s1, col, voc_parts)
        rq, hq = self._explode_all(q, col, voc_parts)
        voc = pl.concat(voc_parts).unique(subset="h").sort("h")
        del voc_parts
        self.hashes = voc["h"].to_numpy()
        self.V = len(self.hashes)
        arr = voc["t"].str.slice(0, 40).to_arrow().cast(pa.large_string())
        bufs = arr.buffers()
        offs = np.frombuffer(bufs[1], dtype=np.int64)[arr.offset: arr.offset + self.V + 1]
        self.voc_ptr = (offs - offs[0]).astype(np.int64)
        self.voc_buf = np.frombuffer(bufs[2], dtype=np.uint8)[offs[0]: offs[-1]].copy()
        self.is_num = voc["t"].str.contains(r"\d").to_numpy()
        self.country_of = voc["country"].to_numpy()
        del voc, arr, bufs
        self.s1_ptr, self.s1_ids = self._csr(r1, h1, s1.height)
        self.q_ptr, self.q_ids = self._csr(rq, hq, q.height)
        del r1, h1, rq, hq
        # statistics (document frequencies in S1 and in S2/S3)
        if stat_col != col:
            ids1 = self._ids(self._explode_all(s1, stat_col, None)[1])
            idsq = self._ids(self._explode_all(q, stat_col, None)[1])
        else:
            ids1, idsq = self.s1_ids, self.q_ids
        df1 = np.bincount(ids1[ids1 >= 0], minlength=self.V).astype(np.float64)
        c23 = np.bincount(idsq[idsq >= 0], minlength=self.V).astype(np.float64)
        del ids1, idsq
        n1 = dict(s1.group_by("country").len().iter_rows())
        nq = dict(q.group_by("country").len().iter_rows())
        cats, inv = np.unique(self.country_of, return_inverse=True)
        N1 = np.array([n1.get(c, 1) for c in cats], np.float64)[inv]
        NQ = np.array([nq.get(c, 1) for c in cats], np.float64)[inv]
        self.df1 = df1.astype(np.float32)
        raw_idf = np.log((N1 + 1.0) / (df1 + 1.0))
        self.idf = np.minimum(np.round(raw_idf / IDF_STEP) * IDF_STEP, IDF_CAP).astype(np.float32)
        self.ratio_raw = (np.log((c23 + 1.0) / (df1 + 1.0)) - np.log(NQ / N1)).astype(np.float32)
        # Shift-robust "sibling" statistic: every benign token maps to exactly 0;
        # only strongly over-represented tokens (raw > 2, i.e. >7x more frequent in
        # S2/S3 than expected) carry signal, in coarse steps.
        self.ratio = np.clip(np.round((self.ratio_raw - SIB_OFFSET) / RATIO_STEP) * RATIO_STEP,
                             0.0, 8.0).astype(np.float32)
        # statistics of the candidate pruner (candidates.py), which was trained on them
        self.idf_pruner = (raw_idf / np.log(N1 + 1.0)).astype(np.float32)
        self.ratio_pruner = np.clip(self.ratio_raw - SIB_OFFSET, 0.0, 8.0).astype(np.float32)

    def _explode_all(self, df, col, voc_parts):
        rs, hs = [], []
        for off in range(0, df.height, self.CHUNK):
            part = df.slice(off, self.CHUNK)
            ex = (part.select(pl.int_range(off, off + part.height, dtype=pl.Int64).alias("r"),
                              "country", pl.col(col).fill_null("").str.split(" ").alias("t"))
                  .explode("t")
                  .filter(pl.col("t").is_not_null() & (pl.col("t").str.len_chars() > 0))
                  .unique(subset=["r", "t"], maintain_order=True)
                  .with_columns(pl.concat_str(["country", "t"], separator="").hash(seed=11).alias("h")))
            if voc_parts is not None:
                voc_parts.append(ex.select("h", "country", "t").unique(subset="h"))
            rs.append(ex["r"].to_numpy())
            hs.append(ex["h"].to_numpy())
            del ex
        return np.concatenate(rs), np.concatenate(hs)

    def _ids(self, h):
        pos = np.searchsorted(self.hashes, h)
        pos = np.minimum(pos, self.V - 1)
        return np.where(self.hashes[pos] == h, pos, -1).astype(np.int32)

    def _csr(self, r, h, n):
        ids = self._ids(h)
        ptr = np.zeros(n + 1, np.int64)
        np.cumsum(np.bincount(r, minlength=n), out=ptr[1:])
        return ptr, ids


